#!/usr/bin/env node
/**
 * Generates the Greasy Fork copy of the userscript.
 *
 * Greasy Fork serves its own update and download URLs, so the @downloadURL /
 * @updateURL keys pointing at GitHub are stripped from the published copy —
 * otherwise installs from Greasy Fork would silently update from GitHub instead.
 *
 *   node tools/build-greasyfork.mjs           write dist/<name>.greasyfork.user.js
 *   node tools/build-greasyfork.mjs --check   exit 1 if the file is out of date
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(root, 'messenger-alt-chat-switcher.user.js');
const OUTPUT = resolve(root, 'dist/messenger-alt-chat-switcher.greasyfork.user.js');
const STRIPPED_KEYS = ['downloadURL', 'updateURL'];

const NOTICE = [
    '',
    '// Generated by tools/build-greasyfork.mjs — do not edit this copy.',
    `// Edit messenger-alt-chat-switcher.user.js instead. ${STRIPPED_KEYS.map(k => '@' + k).join(' and ')}`,
    '// are stripped here because Greasy Fork serves its own update URLs.',
].join('\n');

function build(source) {
    const stripPattern = new RegExp(`^//\\s*@(?:${STRIPPED_KEYS.join('|')})\\b`);
    const lines = source.split('\n');

    const metaEnd = lines.findIndex(line => /^\/\/\s*==\/UserScript==/.test(line));
    if (metaEnd === -1) throw new Error('metadata block end (==/UserScript==) not found');

    const head = lines.slice(0, metaEnd + 1).filter(line => !stripPattern.test(line));
    const tail = lines.slice(metaEnd + 1);

    return [...head, NOTICE, ...tail].join('\n');
}

const built = build(readFileSync(SOURCE, 'utf8'));
const check = process.argv.includes('--check');

if (check) {
    let current = null;
    try {
        current = readFileSync(OUTPUT, 'utf8');
    } catch {
        // Missing output is simply out of date
    }
    if (current === built) {
        console.log('dist copy is up to date');
    } else {
        console.error('dist copy is out of date — run: node tools/build-greasyfork.mjs');
        process.exit(1);
    }
} else {
    writeFileSync(OUTPUT, built);
    console.log(`wrote ${OUTPUT.slice(root.length + 1)}`);
}
